    const fn from_byte(value: u8) -> Self {
        match value % 10 {
            0 => Self::Profile,
            1 => Self::LifecycleShape,
            2 => Self::Lifecycle,
            3 => Self::Wallet,
            4 => Self::Fingerprint,
            5 => Self::Xpub,
            6 => Self::Session,
            7 => Self::Counter,
            8 => Self::Instruction,
            9 => Self::Descriptor,
            _ => unreachable!(),
        }
    }

